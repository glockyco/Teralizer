package teralizer.processing;

public enum ProcessingStage {
    CLEANUP_PROJECT(0),

    DOWNLOAD_PROJECT(1),
    SETUP_PROJECT(2),

    BUILD_PROJECT_ORIGINAL(3),
    GENERATE_TESTS(4),

    BUILD_SPOON_MODEL(5),

    EXECUTE_TESTS_ORIGINAL(6),
    COLLECT_JUNIT_REPORTS_ORIGINAL(7),
    ANALYZE_TESTS(8),
    FILTER_TESTS(9),
    FILTER_ASSERTIONS(10),

    ADD_JPF_INSTRUMENTATION(11),
    BUILD_PROJECT_INSTRUMENTED(12),
    EXECUTE_JPF(13),
    ANALYZE_JPF(14),
    CLEANUP_JPF_INSTRUMENTATION(15),

    ADD_DEPENDENCIES(16),
    BUILD_PROJECT_INITIAL(17),
    EXECUTE_TESTS_INITIAL(18),

    COLLECT_JUNIT_REPORTS_INITIAL(19),
    COLLECT_JACOCO_DATA_INITIAL(20),
    COLLECT_PIT_DATA_INITIAL(21),

    CLEANUP_GENERALIZATION(22),

    GENERALIZE_TESTS(23),
    BUILD_PROJECT_GENERALIZED(24),

    EXECUTE_TESTS_GENERALIZED(25),
    COLLECT_JUNIT_REPORTS_GENERALIZED(26),
    FILTER_GENERALIZATIONS(27),

    COLLECT_JACOCO_DATA_GENERALIZED(28),
    COLLECT_PIT_DATA_GENERALIZED(29);

    private final Integer step;

    ProcessingStage(Integer step) {
        this.step = step;
    }

    public Integer getStep() {
        return this.step;
    }
}
