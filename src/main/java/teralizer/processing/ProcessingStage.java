package teralizer.processing;

public enum ProcessingStage {
    CLEANUP_PROJECT(0),

    DOWNLOAD_PROJECT(1),
    SETUP_PROJECT(2),

    BUILD_PROJECT_ORIGINAL(3),
    GENERATE_TESTS(4),
    EXECUTE_TESTS_ORIGINAL(5),

    COLLECT_JUNIT_TESTS(6),

    ADD_DEPENDENCIES(7),
    BUILD_PROJECT_INITIAL(8),
    EXECUTE_TESTS_INITIAL(9),

    COLLECT_JUNIT_REPORTS_INITIAL(10),
    ANALYZE_TESTS(11),
    FILTER_TESTS(12),

    COLLECT_JACOCO_DATA_INITIAL(13),
    COLLECT_PIT_DATA_INITIAL(14),

    ADD_JPF_INSTRUMENTATION(15),
    BUILD_PROJECT_INSTRUMENTED(16),
    EXECUTE_JPF(17),

    CLEANUP_GENERALIZATION(18),

    GENERALIZE_TESTS(19),
    BUILD_PROJECT_GENERALIZED(20),
    EXECUTE_TESTS_GENERALIZED(21),

    COLLECT_JUNIT_REPORTS_GENERALIZED(22),
    FILTER_GENERALIZATIONS(23),

    COLLECT_JACOCO_DATA_GENERALIZED(24),
    COLLECT_PIT_DATA_GENERALIZED(25);

    private final Integer step;

    ProcessingStage(Integer step) {
        this.step = step;
    }

    public Integer getStep() {
        return this.step;
    }
}
