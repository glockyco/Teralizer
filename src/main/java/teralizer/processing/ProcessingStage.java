package teralizer.processing;

public enum ProcessingStage {
    CLEANUP(null),

    PROJECT_DOWNLOAD(1),
    PROJECT_SETUP(2),
    PROJECT_BUILDING_ORIGINAL(3),
    TEST_EXECUTION_ORIGINAL(4),

    ADD_DEPENDENCIES(5),
    PROJECT_BUILDING_WITH_DEPENDENCIES(6),
    TEST_EXECUTION_WITH_DEPENDENCIES(7),

    COVERAGE_DATA_COLLECTION_ORIGINAL(8),
    MUTATION_DATA_COLLECTION_ORIGINAL(9),

    TEST_DETECTION(10),
    TEST_FILTERING(11),
    TEST_DATA_COLLECTION_ORIGINAL(12),

    JPF_INSTRUMENTATION(13),
    PROJECT_BUILDING_INSTRUMENTED(14),
    JPF_EXECUTION(15),

    TEST_GENERALIZATION(16),
    PROJECT_BUILDING_GENERALIZED(17),
    TEST_EXECUTION_GENERALIZED(18),

    COVERAGE_DATA_COLLECTION_GENERALIZED(19),
    MUTATION_DATA_COLLECTION_GENERALIZED(20),
    TEST_DATA_COLLECTION_GENERALIZED(21);

    private final Integer step;

    ProcessingStage(Integer step) {
        this.step = step;
    }

    public Integer getStep() {
        return this.step;
    }
}
