package teralizer.processing;

public enum ProcessingStage {
    CLEANUP_PROJECT(0),

    DOWNLOAD_PROJECT(1),
    SETUP_PROJECT(2),

    BUILD_PROJECT_ORIGINAL(3),
    EXECUTE_TESTS_ORIGINAL(4),

    COLLECT_JUNIT_TESTS(5),

    ADD_DEPENDENCIES(6),
    BUILD_PROJECT_INITIAL(7),
    EXECUTE_TESTS_INITIAL(8),

    COLLECT_JUNIT_REPORTS_INITIAL(9),
    ANALYZE_TESTS(10),
    FILTER_TESTS(11),

    COLLECT_JACOCO_DATA_INITIAL(12),
    COLLECT_PIT_DATA_INITIAL(13),

    ADD_JPF_INSTRUMENTATION(14),
    BUILD_PROJECT_INSTRUMENTED(15),
    EXECUTE_JPF(16),

    CLEANUP_GENERALIZATION(17),

    GENERALIZE_TESTS(18),
    BUILD_PROJECT_GENERALIZED(19),
    EXECUTE_TESTS_GENERALIZED(20),

    COLLECT_JUNIT_REPORTS_GENERALIZED(21),
    FILTER_GENERALIZATIONS(22),

    COLLECT_JACOCO_DATA_GENERALIZED(23),
    COLLECT_PIT_DATA_GENERALIZED(24);

    private final Integer step;

    ProcessingStage(Integer step) {
        this.step = step;
    }

    public Integer getStep() {
        return this.step;
    }
}
