package teralizer.processing;

public enum ProcessingStage {
    CLEANUP_PROJECT(0),

    DOWNLOAD_PROJECT(1),
    SETUP_PROJECT(2),

    BUILD_PROJECT_ORIGINAL(3),
    GENERATE_TESTS(4),

    EXECUTE_TESTS_ORIGINAL(5),
    COLLECT_JUNIT_REPORTS_ORIGINAL(6),
    ANALYZE_TESTS(7),
    FILTER_TESTS(8),

    ADD_JPF_INSTRUMENTATION(9),
    BUILD_PROJECT_INSTRUMENTED(10),
    EXECUTE_JPF(11),

    ADD_DEPENDENCIES(12),
    BUILD_PROJECT_INITIAL(13),
    EXECUTE_TESTS_INITIAL(14),

    COLLECT_JUNIT_REPORTS_INITIAL(15),
    COLLECT_JACOCO_DATA_INITIAL(16),
    COLLECT_PIT_DATA_INITIAL(17),

    CLEANUP_GENERALIZATION(18),

    GENERALIZE_TESTS(19),
    BUILD_PROJECT_GENERALIZED(20),

    EXECUTE_TESTS_GENERALIZED(21),
    COLLECT_JUNIT_REPORTS_GENERALIZED(22),
    FILTER_GENERALIZATIONS(23),

    COLLECT_JACOCO_DATA_GENERALIZED(24),
    COLLECT_PIT_DATA_GENERALIZED(25);

    private final Integer step;

    ProcessingStage(Integer step) {
        this.step = step;
    }

    public Integer getStep() {
        return this.step;
    }
}
